export function applyEffects(stats: Strengths, effects: Partial<Strengths>): Strengths {
  const next = { ...stats };
  for (const key of STRENGTH_KEYS) {
    const delta = effects[key];
    if (delta) {
      next[key] = Math.max(0, Math.min(MAX_STRENGTH, next[key] + delta));
    }
  }
  return next;
}

export function effectOf(key: StrengthKey, value: number): Partial<Strengths> {
  return { [key]: value } as Partial<Strengths>;
}

export type Stars = 1 | 2 | 3;

export function starsFromScore(score: number): Stars {
  if (score >= 0.85) return 3;
  if (score >= 0.5) return 2;
  return 1;
}

